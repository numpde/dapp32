import assert from 'node:assert/strict'
import { finishDisplayFixture } from './escrow-browser-fixture.mjs'
import { assertStableLayout } from './layout-stability.mjs'

export async function checkNftMetadata({ call, evaluate, viewerURL }) {
  const fixture = new URL('/test/nft-metadata-fixture.html', viewerURL)
  fixture.search = new URL(viewerURL).search
  const editor = '.nft-editor'
  const json = `${editor} textarea[name="tokenURI.metadata.json"]`
  async function wait(expression) {
    const deadline = Date.now() + 10000
    while (Date.now() < deadline) {
      if (await evaluate(expression)) return
      await new Promise(resolve => setTimeout(resolve, 50))
    }
    assert.fail(`NFT fixture did not reach: ${expression}`)
  }
  async function click(selector, text) {
    // silent-defaults: allow-default -- Controls with icon-only labels are located by aria-label; text labels identify the others.
    assert(await evaluate(`(() => { const button = [...document.querySelectorAll(${JSON.stringify(selector)})].find(node => (node.getAttribute('aria-label')??node.textContent) === ${JSON.stringify(text)}); if (!button) return false; button.click(); return true })()`), `control exists: ${text}`)
  }
  async function edit(selector, value) {
    await evaluate(`(() => { const node=document.querySelector(${JSON.stringify(selector)}); const prototype=node instanceof HTMLTextAreaElement ? HTMLTextAreaElement.prototype : HTMLInputElement.prototype; Object.getOwnPropertyDescriptor(prototype,'value').set.call(node,${JSON.stringify(value)}); node.dispatchEvent(new Event('input',{bubbles:true})) })()`)
  }
  const failures = []
  try {
    await call('Page.navigate', { url: fixture.href })
    await wait(`!!window.nftFixture&&document.querySelectorAll('.nft-editor').length===2`)
    assert(await evaluate(`document.querySelector('.nft-editor [role="tablist"]').children.length===2`), 'metadata offers hosted and embedded preparation tabs')
    const selectedURI = await evaluate('window.nftFixture.uri()')
    await click(`${editor} [role="tab"]`, 'Embed JSON')
    assert.equal(await evaluate('window.nftFixture.uri()'), selectedURI, 'changing preparation tabs does not change the submitted URI')
    assert(await evaluate(`!document.querySelector('.nft-editor input[name="tokenURI"]')`), 'embedded preparation does not show a competing hosted URI input')
    await click(`${editor} [role="tab"]`, 'Hosted JSON')
    await evaluate(`document.querySelector('.nft-editor [role="tab"]').dispatchEvent(new KeyboardEvent('keydown',{key:'ArrowRight',bubbles:true}))`)
    assert(await evaluate(`document.activeElement.textContent==='Embed JSON'&&document.activeElement.getAttribute('aria-selected')==='true'`), 'arrow keys select and focus the next tab')
    await evaluate(`document.activeElement.dispatchEvent(new KeyboardEvent('keydown',{key:'Home',bubbles:true}))`)
    assert(await evaluate(`document.activeElement.textContent==='Hosted JSON'&&document.activeElement.getAttribute('aria-selected')==='true'`), 'Home returns focus and selection to the first tab')
    assert(await evaluate(`window.nftFixture.requests.length===0&&!document.querySelector('.nft-row .nft-preview')&&!document.querySelector('img')`), 'rendering performs no automatic metadata or image fetch')
    assert(await evaluate(`(() => { const preview=document.querySelector('section.nft-row[aria-label="NFT"]');return !!preview?.querySelector('.nft-placeholder')&&!!preview.querySelector('.nft-identity')&&[...preview.querySelectorAll('button')].some(button=>button.textContent==='Load preview') })()`), 'the unloaded NFT groups its identity, source and loading action in one preview area')
    await click('.nft-row button', 'Load preview')
    await wait(`!!document.querySelector('.nft-row .nft-preview h3')`)
    assert(await evaluate(`!!document.querySelector('section.nft-row[aria-label="NFT"] .nft-preview')&&!document.querySelector('.nft-row .nft-placeholder')`), 'loaded content replaces the placeholder within the same NFT area')
    await wait(`document.querySelector('.nft-row img')?.naturalWidth===2`)
    assert(await evaluate(`(() => { const preview=document.querySelector('.nft-row .nft-preview');const details=document.querySelector('.nft-row .nft-details');return !!details&&preview.getBoundingClientRect().bottom<=details.getBoundingClientRect().top+1 })()`), 'loaded content leads the preview, followed by its details')
    assert(await evaluate(`[...document.querySelectorAll('.nft-row button')].some(button=>button.textContent==='Reload preview')&&![...document.querySelectorAll('.nft-row .nft-image button')].some(button=>button.getClientRects().length&&getComputedStyle(button).visibility!=='hidden')`), 'success offers reload without a redundant image-loading action')
    assert(await evaluate(`window.nftFixture.requests.length===1&&window.nftFixture.requests[0]===window.nftFixture.metadata.image`), 'loading an NFT fetches and decodes its image without a second action')

    await click(`${editor} summary`, 'Prepare JSON for hosting')
    await click(`${editor} button`, 'Load selected metadata')
    await wait(`document.querySelector(${JSON.stringify(json)}).value.includes('retained')`)
    const importAnchors = { name: 'input[name="tokenURI.metadata.name"]', json, following: '.nft-editor[disabled]' }
    try {
      await assert.rejects(assertStableLayout(evaluate, importAnchors, () => evaluate(`(() => {
        const row=document.createElement('p');row.id='injected-loading-row';row.textContent='Loading…';
        const field=document.querySelector('input[name="tokenURI.metadata.name"]').closest('label');field.before(row)
      })()`), 'injected loading row'), /name moved or resized/)
    } finally { await evaluate(`document.getElementById('injected-loading-row')?.remove()`) }
    await evaluate(`window.nftFixture.holdMetadata()`)
    await assertStableLayout(evaluate, importAnchors, async () => {
      await click(`${editor} button`, 'Load selected metadata')
      await wait(`[...document.querySelectorAll('.nft-editor button')].find(e=>e.getAttribute('aria-label')==='Load selected metadata'||e.textContent==='Load selected metadata').disabled`)
    }, 'metadata import pending')
    await evaluate(`document.querySelector('input[name="tokenURI.metadata.name"]').focus()`)
    await edit('input[name="tokenURI.metadata.name"]', 'Edited during import')
    await evaluate(`window.nftFixture.releaseMetadata()`)
    assert.equal(await evaluate(`JSON.parse(document.querySelector(${JSON.stringify(json)}).value).name`), 'Edited during import', 'a late import cannot replace newer edits')
    assert.equal(await evaluate('document.activeElement.name'), 'tokenURI.metadata.name', 'cancelling an import by editing keeps focus in the edited field')
    await evaluate(`window.nftFixture.response(JSON.stringify({...window.nftFixture.metadata,image:'./image.png'}))`)
    await click(`${editor} button`, 'Load selected metadata')
    await wait(`document.querySelector('input[name="tokenURI.metadata.image"]').value==='./image.png'`)
    await click(`${editor} button`, 'Load image')
    await wait(`document.querySelector('.nft-editor img')?.naturalWidth===2`)
    await click(`${editor} [role="tab"]`, 'Embed JSON')
    assert(await evaluate(`[...document.querySelectorAll('.nft-editor button')].find(e=>e.textContent==='Use embedded JSON').disabled`), 'relative images retain their import base for preview and cannot silently become inline metadata')
    const beforeOversize = await evaluate(`document.querySelector(${JSON.stringify(json)}).value`)
    await evaluate(`window.nftFixture.response(JSON.stringify({values:Array(60000).fill(0)}))`)
    await click(`${editor} button`, 'Load selected metadata')
    await wait(`[...document.querySelectorAll('.nft-editor [role="alert"]')].some(e=>e.textContent.includes('256 KiB'))`)
    assert.equal(await evaluate(`document.querySelector(${JSON.stringify(json)}).value`), beforeOversize, 'an import too large after formatting preserves the previous draft')
    await evaluate(`window.nftFixture.response(undefined)`)
    await click(`${editor} button`, 'Load selected metadata')
    await wait(`document.querySelector('input[name="tokenURI.metadata.image"]').value===window.nftFixture.metadata.image`)
    await edit('input[name="tokenURI.metadata.name"]', 'Edited NFT')
    await edit('input[name="tokenURI.metadata.description"]', 'An edited description')
    await edit('input[name="tokenURI.metadata.image"]', 'https://nft.fixture.test/other.png')
    await wait(`document.querySelector(${JSON.stringify(json)}).value.includes('other.png')`)
    const exported = await evaluate(`JSON.stringify(JSON.parse(document.querySelector(${JSON.stringify(json)}).value),null,2)+String.fromCharCode(10)`)
    const document = JSON.parse(exported)
    assert.equal(document.name, 'Edited NFT')
    assert.equal(document.description, 'An edited description')
    assert.equal(document.image, 'https://nft.fixture.test/other.png')
    assert.deepEqual(document.extra, { retained: true })
    assert.deepEqual(document.attributes, [{ trait_type: 'Year', value: 2026, display_type: 'number', extension: true }])
    await click(`${editor} button`, 'Copy JSON')
    await wait(`window.nftFixture.copies.length===1`)
    assert.equal(await evaluate(`window.nftFixture.copies[0]`), exported, 'copy uses the exact displayed JSON document')
    await click(`${editor} button`, 'Download JSON')
    await wait(`window.nftFixture.downloads.length===1`)
    assert.equal(await evaluate(`window.nftFixture.downloads[0]`), exported, 'download preserves JSON bytes')
    assert(await evaluate(`window.nftFixture.uri()===window.nftFixture.publishedURI`), 'copy and download do not change the transaction URI')
    await click(`${editor} button`, 'Use embedded JSON')
    await click(`${editor} summary`, 'URI to submit')
    await click(`${editor} button`, 'Copy URI')
    await wait(`window.nftFixture.copies.length===2`)
    const inline = await evaluate(`window.nftFixture.copies[1]`)
    assert.equal(Buffer.from(inline.split(',')[1], 'base64').toString('utf8'), exported)
    assert.equal(await evaluate(`document.querySelector('.nft-editor textarea[readonly]').value`), inline)
    await wait(`window.nftFixture.uri()===${JSON.stringify(inline)}`)
    await click(`${editor} [role="tab"]`, 'Hosted JSON')
    assert.equal(await evaluate(`document.querySelector('input[name="tokenURI"]').value`), selectedURI, 'hosted draft survives selecting an embedded document')
    assert.equal(await evaluate(`window.nftFixture.uri()`), inline, 'opening the hosted tab does not silently reselect its URI')
    await edit('input[name="tokenURI"]', inline)
    assert(await evaluate(`[...document.querySelectorAll('.nft-editor button')].find(e=>e.textContent==='Use hosted JSON').disabled&&document.querySelector('.nft-editor [role="alert"]').textContent.includes('Embed JSON')`), 'embedded bytes cannot be selected under a hosted-source label')
    assert.equal(await evaluate(`window.nftFixture.uri()`), inline, 'editing another source draft preserves the selected embedded source')
    await click(`${editor} [role="tab"]`, 'Embed JSON')
    await edit('input[name="tokenURI.metadata.name"]', 'Later draft')
    await wait(`window.nftFixture.uri()===''`)
    await click(`${editor} [role="tab"]`, 'Hosted JSON')
    await edit('input[name="tokenURI"]', 'https://nft.fixture.test/manual.json')
    assert.equal(await evaluate(`window.nftFixture.uri()`), '', 'editing a hosted draft does not select it')
    await click(`${editor} button`, 'Use hosted JSON')
    await click(`${editor} [role="tab"]`, 'Embed JSON')
    await edit('input[name="tokenURI.metadata.description"]', 'Unpublished changes')
    assert.equal(await evaluate(`window.nftFixture.uri()`), 'https://nft.fixture.test/manual.json', 'editing a draft preserves a manually supplied URI')
    await click(`${editor} [role="tab"]`, 'Hosted JSON')
    await edit('input[name="tokenURI"]', 'https://nft.fixture.test/revised.json')
    assert.equal(await evaluate(`window.nftFixture.uri()`), '', 'editing the selected hosted URI requires explicit reapplication')
    await click(`${editor} button`, 'Use hosted JSON')
    assert.equal(await evaluate(`window.nftFixture.uri()`), 'https://nft.fixture.test/revised.json')

    assert(await evaluate(`[...document.querySelectorAll('.nft-editor')][1].querySelectorAll('input,textarea,button').length>0&&[...[...document.querySelectorAll('.nft-editor')][1].querySelectorAll('input,textarea,button')].every(node=>node.matches(':disabled'))`), 'field disablement reaches all nested controls')
    await evaluate(`window.nftFixture.busy(true)`)
    await wait(`document.querySelector('.elements').disabled`)
    assert(await evaluate(`[...document.querySelectorAll('.elements input,.elements textarea,.elements button')].every(node=>node.matches(':disabled'))`), 'view transition disables NFT loading and all editor controls')
    await evaluate(`window.nftFixture.busy(false)`)
    await wait(`!document.querySelector('.elements').disabled`)

    for (const kind of ['account', 'route']) {
      if (!(await evaluate(`!!document.querySelector('.nft-row .nft-preview')`))) {
        await click('.nft-row button', 'Load preview')
        await wait(`!!document.querySelector('.nft-row .nft-preview')`)
        await wait(`document.querySelector('.nft-row img')?.naturalWidth===2`)
      }
      await click(`${editor} [role="tab"]`, 'Embed JSON')
      await edit(json, '{"name":"Local draft to discard"}')
      const imageURL = await evaluate(`document.querySelector('.nft-row img').src`)
      await evaluate(`window.nftFixture.scope(${JSON.stringify(kind)})`)
      await wait(`!document.querySelector('.nft-row .nft-preview')&&document.querySelector(${JSON.stringify(json)}).value==='{}'`)
      assert(await evaluate(`window.nftFixture.revoked.includes(${JSON.stringify(imageURL)})`), `${kind} change clears previews and drafts and revokes image resources`)
    }
    const inlineImage = await evaluate(`(() => { const canvas=document.createElement('canvas');canvas.width=2;canvas.height=2;return canvas.toDataURL('image/png') })()`)
    const beforeInline = await evaluate(`window.nftFixture.requests.length`)
    await click(`${editor} [role="tab"]`, 'Embed JSON')
    await edit(json, JSON.stringify({ image: inlineImage }))
    await wait(`document.querySelector('.nft-editor img')?.naturalWidth===2`)
    await evaluate(`window.nftFixture.image(${JSON.stringify(inlineImage)})`)
    await click('.nft-row button', 'Load preview')
    await wait(`document.querySelector('.nft-row img')?.naturalWidth===2`)
    assert.equal(await evaluate(`window.nftFixture.requests.length`), beforeInline, 'embedded viewer images decode automatically without network requests')
    const inlineURL = await evaluate(`document.querySelector('.nft-editor img').src`)
    await edit(json, '{"image":"https://nft.fixture.test/image.png"}')
    await wait(`!document.querySelector('.nft-editor img')`)
    assert(await evaluate(`window.nftFixture.revoked.includes(${JSON.stringify(inlineURL)})&&window.nftFixture.requests.length===${beforeInline}`), 'replacing an embedded image revokes its URL and does not automatically fetch a remote image')
    await edit(json, '{"name":"<img src=x onerror=alert(1)>","description":"<script>alert(1)</script>","image":"data:image/svg+xml,%3Csvg%20xmlns=%22http://www.w3.org/2000/svg%22/%3E"}')
    await wait(`!!document.querySelector('.nft-editor .nft-image [role="alert"]')`)
    assert(await evaluate(`!document.querySelector('.nft-editor img')&&!document.querySelector('.nft-editor svg')&&document.querySelector('.nft-editor .nft-image [role="alert"]').textContent.includes('SVG')`), 'SVG image bytes fail visibly without rendering active content')
    assert(await evaluate(`document.querySelector('.nft-editor h3').textContent==='<img src=x onerror=alert(1)>'&&!document.querySelector('.nft-editor .nft-preview script')`), 'metadata text is rendered as text rather than active HTML')
    await evaluate(`window.nftFixture.image('data:image/svg+xml,%3Csvg/%3E')`)
    await click('.nft-row button', 'Load preview')
    await wait(`!!document.querySelector('.nft-row .nft-image [role="alert"]')`)
    assert(await evaluate(`document.querySelector('.nft-row h3').textContent==='Fixture NFT'&&!document.querySelector('.nft-row img')`), 'an image failure stays inside the NFT and preserves its metadata')
    const beforeRejected = await evaluate('window.nftFixture.requests.length')
    await click(`${editor} [role="tab"]`, 'Hosted JSON')
    await edit('input[name="tokenURI"]', 'not a URL')
    await click(`${editor} button`, 'Use hosted JSON')
    await click(`${editor} summary`, 'Prepare JSON for hosting')
    await click(`${editor} button`, 'Load selected metadata')
    const resourceError = '.nft-hosted-draft > .error-feedback'
    await wait(`!!document.querySelector(${JSON.stringify(resourceError + '[role="alert"]')})`)
    const primary = await evaluate(`document.querySelector(${JSON.stringify(resourceError + ' .feedback-message')}).textContent`)
    assert.match(primary, /Cannot load.*http:\/\/.*https:\/\//)
    assert.doesNotMatch(primary, /construct|expected absolute|Invalid URL/)
    assert(await evaluate(`!document.querySelector(${JSON.stringify(resourceError + ' details')})&&document.querySelector(${JSON.stringify(resourceError + ' code')}).textContent.includes('expected absolute URL')`), 'the precise URL diagnostic is visible without a disclosure')
    assert.equal(await evaluate('window.nftFixture.uri()'), 'not a URL', 'a preview failure preserves the selected URI')
    await edit('input[name="tokenURI"]', 'https://person:private-password@example.test/meta.json?token=private-token')
    await click(`${editor} button`, 'Use hosted JSON')
    await click(`${editor} button`, 'Load selected metadata')
    await wait(`document.querySelector(${JSON.stringify(resourceError + ' code')})?.textContent.includes('credentials')`)
    assert(await evaluate(`!document.querySelector(${JSON.stringify(resourceError)}).textContent.includes('private-password')&&!document.querySelector(${JSON.stringify(resourceError)}).textContent.includes('private-token')`), 'friendly and technical error text exclude credentials and tokens')
    await edit(json, '{bad JSON}')
    await wait(`[...document.querySelectorAll('.nft-editor [role="alert"]')].some(e=>e.textContent.includes('use valid JSON'))`)
    assert(await evaluate(`[...document.querySelectorAll('.nft-editor .feedback-message')].every(e=>!e.textContent.includes('Unexpected token'))`), 'local JSON errors lead with the correction while retaining the cause below')
    assert.equal(await evaluate('window.nftFixture.requests.length'), beforeRejected, 'rejected resource addresses never issue a request')
    await edit(json, '{"name":"Copy failure test"}')
    await evaluate(`window.nftFixture.rejectCopy(true)`)
    await click(`${editor} button`, 'Copy JSON')
    await wait(`[...document.querySelectorAll('.nft-editor [role="alert"]')].some(e=>e.textContent.includes('Cannot copy'))`)
    assert(await evaluate(`[...document.querySelectorAll('.nft-editor .error-feedback code')].some(e=>e.textContent.includes('Permission denied'))`), 'clipboard reporting preserves the provider cause')
    await click(`${editor} button`, 'Download JSON')
    await wait(`[...document.querySelectorAll('.nft-editor [role="status"]')].some(e=>e.textContent.includes('download requested'))`)
    assert(await evaluate(`![...document.querySelectorAll('.nft-editor [role="alert"]')].some(e=>e.textContent.includes('Cannot copy'))`), 'later success replaces the previous clipboard failure')
    await evaluate(`window.nftFixture.source(window.nftFixture.publishedURI);window.nftFixture.holdMetadata()`)
    await click('.nft-row button', 'Load preview')
    await wait(`!!document.querySelector('.nft-row button[aria-busy="true"]:disabled')`)
    await click('.nft-row button', 'Cancel loading')
    await evaluate(`window.nftFixture.releaseMetadata();window.nftFixture.response('{broken')`)
    await click('.nft-row button', 'Load preview')
    await wait(`[...document.querySelectorAll('.nft-row button')].some(button=>button.textContent==='Retry loading')`)
    await evaluate(`window.nftFixture.response(undefined);window.nftFixture.holdMetadata()`)
    await assertStableLayout(evaluate, { error: '.nft-row [role="alert"]', details: '.nft-row .nft-details', following: '.nft-editor:not([disabled])' }, async () => {
      await click('.nft-row button', 'Retry loading')
      await wait(`!!document.querySelector('.nft-row button[aria-busy="true"]')`)
    }, 'failed preview retry pending')
    await evaluate(`window.nftFixture.releaseMetadata()`)
    await wait(`document.querySelector('.nft-row img')?.naturalWidth===2`)
    assert(await evaluate(`!document.querySelector('.nft-row [role="alert"]')&&[...document.querySelectorAll('.nft-row button')].some(button=>button.textContent==='Reload preview')`), 'retry recovers the preview and clears the failed state')
    for (const width of [1280, 320]) {
      await call('Emulation.setDeviceMetricsOverride', { width, height: 900, deviceScaleFactor: 1, mobile: width === 320 })
      const anchors = { image: '.nft-row img', details: '.nft-row .nft-details', following: '.nft-editor:not([disabled])' }
      const displayedImage = await evaluate(`document.querySelector('.nft-row img').src`)
      await evaluate(`window.nftFixture.holdMetadata()`)
      await assertStableLayout(evaluate, anchors, async () => {
        await click('.nft-row button', 'Reload preview')
        await wait(`!!document.querySelector('.nft-row button[aria-busy="true"]')`)
      }, `${width}px metadata reload pending`)
      await evaluate(`document.querySelector('.nft-row .nft-details .resource-cancel').focus()`)
      await assertStableLayout(evaluate, anchors, () => click('.nft-row .nft-details button', 'Cancel loading'), `${width}px metadata reload cancelled`)
      await wait(`document.activeElement===document.querySelector('.nft-row .nft-details .resource-load')`)
      await evaluate(`window.nftFixture.releaseMetadata();window.nftFixture.holdImage()`)
      await assertStableLayout(evaluate, anchors, async () => {
        await click('.nft-row button', 'Reload preview')
        await wait(`!!document.querySelector('.nft-row .nft-image button[aria-hidden="false"]:not(:disabled)')`)
      }, `${width}px image reload pending`)
      await assertStableLayout(evaluate, anchors, () => click('.nft-row .nft-image button', 'Cancel loading'), `${width}px image reload cancelled`)
      await evaluate(`window.nftFixture.releaseImage()`)
      assert.equal(await evaluate(`document.querySelector('.nft-row img').src`), displayedImage, 'pending reloads and cancellation retain the usable image URL')
    }
    await call('Emulation.setDeviceMetricsOverride', { width: 320, height: 900, deviceScaleFactor: 1, mobile: true })
    assert(await evaluate(`document.documentElement.scrollWidth<=innerWidth`), 'metadata JSON and long URIs fit a 320px viewport')
    return { explicitResourceLoading: true, metadataRoundTrip: true, publicationURIHonest: true, scopeCleanup: true, disabledControls: true, width: 320 }
  } catch (error) {
    failures.push(error)
  } finally {
    await finishDisplayFixture({ call, evaluate, viewerURL, failures })
  }
}
